#!/usr/bin/env bash
# Builds crates/accord-check (accord-core's check_pay over an agreement's views) to wasm and writes it into the SDK as
# packages/sdk/src/check-wasm.ts, which `@accord/sdk/check` runs. Rerun after any change to accord-core's gates or to
# accord-check; `make check-wasm` does, and fails when the committed module differs from a fresh build (CHECK=1).
set -euo pipefail
cd "$(dirname "$0")/.."
# Paths remapped, so the module carries no machine's home or checkout path and builds the same anywhere.
RUSTFLAGS="--remap-path-prefix=$HOME/.cargo=/cargo --remap-path-prefix=$PWD=/accord" \
  cargo build -q --release --locked --target wasm32-unknown-unknown -p accord-check
wasm=target/wasm32-unknown-unknown/release/accord_check.wasm
sha=$(shasum -a 256 "$wasm" | cut -d' ' -f1)
out=packages/sdk/src/check-wasm.ts
tmp=$(mktemp)
{
  echo "// Generated by scripts/build-check-wasm.sh from crates/accord-check (accord-core's check_pay). Do not edit."
  echo "export const CHECK_WASM_SHA256 = \"$sha\";"
  printf 'export const CHECK_WASM_BASE64 =\n  "%s";\n' "$(base64 < "$wasm" | tr -d '\n')"
} > "$tmp"
if [ "${CHECK:-}" = 1 ]; then
  if cmp -s "$tmp" "$out"; then echo "check-wasm: $out matches a fresh build (sha256 ${sha:0:16}…)"; rm "$tmp"; exit 0; fi
  echo "check-wasm: $out differs from a fresh build (sha256 ${sha:0:16}…); run make check-wasm"; rm "$tmp"; exit 1
fi
mv "$tmp" "$out"
printf 'check-wasm: %s  %s bytes  sha256 %s…\n' "$out" "$(wc -c < "$wasm" | tr -d ' ')" "${sha:0:16}"
